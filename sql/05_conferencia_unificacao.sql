/*
 * Conferência pós-carga da unificação de endereços
 * (cidades, distritos e bairros). Somente consultas — pode rodar à vontade.
 *
 * O que se espera de uma carga saudável:
 *   A) "pendentes" diminuindo a cada rodada e "vinculados" perto do total;
 *   B) ZERO linhas nas consultas de código em mais de uma linha;
 *   C) ZERO bairros/distritos vinculados a linha sem código dos Correios.
 */

-------------------------------------------------------------------------------
-- A. Totais por origem: quantos existem na origem e quantos estão vinculados
-------------------------------------------------------------------------------

-- A.1 Cidades
SELECT 'PES' ORIGEM, COUNT(*) TOTAL,
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.CIDADES_UNIFICADO U WHERE U.CIDADE_PESSOA = O.CIDADE) THEN 1 ELSE 0 END) VINCULADOS
  FROM DBO_UNI_PESSOAS.PES_CIDADES O
UNION ALL
SELECT 'RH', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.CIDADES_UNIFICADO U WHERE U.CIDADE_RH = O.CIDADE) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.RH_CIDADES O
UNION ALL
SELECT 'SANE', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.CIDADES_UNIFICADO U WHERE U.CIDADE_SANE = O.CIDADE) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SANE_CIDADES O
UNION ALL
SELECT 'SAU', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.CIDADES_UNIFICADO U WHERE U.CIDADE_SAUDE = O.CIDADE) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SAU_CIDADES O;

-- A.2 Distritos
SELECT 'PES' ORIGEM, COUNT(*) TOTAL,
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO U
                              WHERE U.CIDADE_PESSOA = O.CIDADE AND U.DISTRITO_PESSOA = O.DISTRITO) THEN 1 ELSE 0 END) VINCULADOS
  FROM DBO_UNI_PESSOAS.PES_DISTRITOS O
UNION ALL
SELECT 'RH', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO U
                              WHERE U.CIDADE_RH = O.CIDADE AND U.DISTRITO_RH = O.DISTRITO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.RH_DISTRITOS O
UNION ALL
SELECT 'SANE', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO U
                              WHERE U.CIDADE_SANE = O.CIDADE AND U.DISTRITO_SANE = O.DISTRITO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SANE_DISTRITOS O
UNION ALL
SELECT 'SAU', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO U
                              WHERE U.CIDADE_SAUDE = O.CIDADE AND U.DISTRITO_SAUDE = O.DISTRITO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SAU_DISTRITOS O;

-- A.3 Bairros
SELECT 'PES' ORIGEM, COUNT(*) TOTAL,
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO U
                              WHERE U.CIDADE_PESSOA = O.CIDADE AND U.DISTRITO_PESSOA = O.DISTRITO
                                AND U.BAIRRO_PESSOA = O.BAIRRO) THEN 1 ELSE 0 END) VINCULADOS
  FROM DBO_UNI_PESSOAS.PES_BAIRROS O
UNION ALL
SELECT 'RH', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO U
                              WHERE U.CIDADE_RH = O.CIDADE AND U.DISTRITO_RH = O.DISTRITO
                                AND U.BAIRRO_RH = O.BAIRRO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.RH_BAIRROS O
UNION ALL
SELECT 'SANE', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO U
                              WHERE U.CIDADE_SANE = O.CIDADE AND U.DISTRITO_SANE = O.DISTRITO
                                AND U.BAIRRO_SANE = O.BAIRRO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SANE_BAIRROS O
UNION ALL
SELECT 'SAU', COUNT(*),
       SUM(CASE WHEN EXISTS (SELECT 1 FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO U
                              WHERE U.CIDADE_SAUDE = O.CIDADE AND U.DISTRITO_SAUDE = O.DISTRITO
                                AND U.BAIRRO_SAUDE = O.BAIRRO) THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.SAU_BAIRROS O;

-------------------------------------------------------------------------------
-- B. Código de origem gravado em MAIS DE UMA linha (esperado: nenhuma linha)
--    A migração de pessoas usa getSingleResult e falha nesses casos.
-------------------------------------------------------------------------------

SELECT 'DISTRITO' NIVEL, 'PES' ORIGEM, COUNT(*) QTD_CODIGOS_REPETIDOS FROM (
  SELECT CIDADE_PESSOA, DISTRITO_PESSOA FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO
   WHERE NVL(DISTRITO_PESSOA, 0) > 0 GROUP BY CIDADE_PESSOA, DISTRITO_PESSOA HAVING COUNT(*) > 1)
UNION ALL
SELECT 'DISTRITO', 'RH', COUNT(*) FROM (
  SELECT CIDADE_RH, DISTRITO_RH FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO
   WHERE NVL(DISTRITO_RH, 0) > 0 GROUP BY CIDADE_RH, DISTRITO_RH HAVING COUNT(*) > 1)
UNION ALL
SELECT 'DISTRITO', 'SAU', COUNT(*) FROM (
  SELECT CIDADE_SAUDE, DISTRITO_SAUDE FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO
   WHERE NVL(DISTRITO_SAUDE, 0) > 0 GROUP BY CIDADE_SAUDE, DISTRITO_SAUDE HAVING COUNT(*) > 1)
UNION ALL
SELECT 'DISTRITO', 'SANE', COUNT(*) FROM (
  SELECT CIDADE_SANE, DISTRITO_SANE FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO
   WHERE NVL(DISTRITO_SANE, 0) > 0 GROUP BY CIDADE_SANE, DISTRITO_SANE HAVING COUNT(*) > 1)
UNION ALL
SELECT 'BAIRRO', 'PES', COUNT(*) FROM (
  SELECT CIDADE_PESSOA, DISTRITO_PESSOA, BAIRRO_PESSOA FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO
   WHERE NVL(BAIRRO_PESSOA, 0) > 0 GROUP BY CIDADE_PESSOA, DISTRITO_PESSOA, BAIRRO_PESSOA HAVING COUNT(*) > 1)
UNION ALL
SELECT 'BAIRRO', 'RH', COUNT(*) FROM (
  SELECT CIDADE_RH, DISTRITO_RH, BAIRRO_RH FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO
   WHERE NVL(BAIRRO_RH, 0) > 0 GROUP BY CIDADE_RH, DISTRITO_RH, BAIRRO_RH HAVING COUNT(*) > 1)
UNION ALL
SELECT 'BAIRRO', 'SAU', COUNT(*) FROM (
  SELECT CIDADE_SAUDE, DISTRITO_SAUDE, BAIRRO_SAUDE FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO
   WHERE NVL(BAIRRO_SAUDE, 0) > 0 GROUP BY CIDADE_SAUDE, DISTRITO_SAUDE, BAIRRO_SAUDE HAVING COUNT(*) > 1)
UNION ALL
SELECT 'BAIRRO', 'SANE', COUNT(*) FROM (
  SELECT CIDADE_SANE, DISTRITO_SANE, BAIRRO_SANE FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO
   WHERE NVL(BAIRRO_SANE, 0) > 0 GROUP BY CIDADE_SANE, DISTRITO_SANE, BAIRRO_SANE HAVING COUNT(*) > 1);

-------------------------------------------------------------------------------
-- C. Linhas com código de origem mas SEM código dos Correios (esperado: zero)
-------------------------------------------------------------------------------

SELECT 'DISTRITO' NIVEL, COUNT(*) QTD
  FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO
 WHERE (NVL(CIDADE_CORREIOS, 0) = 0 OR NVL(DISTRITO_CORREIOS, 0) = 0)
   AND (NVL(DISTRITO_PESSOA, 0) + NVL(DISTRITO_RH, 0) + NVL(DISTRITO_SAUDE, 0) + NVL(DISTRITO_SANE, 0)) > 0
UNION ALL
SELECT 'BAIRRO', COUNT(*)
  FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO
 WHERE (NVL(CIDADE_CORREIOS, 0) = 0 OR NVL(BAIRRO_CORREIOS, 0) = 0)
   AND (NVL(BAIRRO_PESSOA, 0) + NVL(BAIRRO_RH, 0) + NVL(BAIRRO_SAUDE, 0) + NVL(BAIRRO_SANE, 0)) > 0;

-------------------------------------------------------------------------------
-- D. Decisões registradas na tela (duplicados e não vincular), por nível
-------------------------------------------------------------------------------

SELECT 'CIDADE' NIVEL, ORIGEM, STATUS, COUNT(*) QTD FROM DBO_UNI_PESSOAS.CIDADES_UNIFICADO_CTRL GROUP BY ORIGEM, STATUS
UNION ALL
SELECT 'DISTRITO', ORIGEM, STATUS, COUNT(*) FROM DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO_CTRL GROUP BY ORIGEM, STATUS
UNION ALL
SELECT 'BAIRRO', ORIGEM, STATUS, COUNT(*) FROM DBO_UNI_PESSOAS.BAIRROS_UNIFICADO_CTRL GROUP BY ORIGEM, STATUS
ORDER BY 1, 2, 3;

-------------------------------------------------------------------------------
-- E. Amostra para conferência visual: 30 distritos PES vinculados,
--    lado a lado com o nome dos Correios (os nomes devem "bater")
-------------------------------------------------------------------------------

SELECT * FROM (
  SELECT O.CIDADE, O.DISTRITO, O.NOME AS NOME_ORIGEM,
         U.CIDADE_CORREIOS, U.DISTRITO_CORREIOS, U.NOME AS NOME_CORREIOS
    FROM DBO_UNI_PESSOAS.PES_DISTRITOS O
    JOIN DBO_UNI_PESSOAS.DISTRITOS_UNIFICADO U
      ON U.CIDADE_PESSOA = O.CIDADE AND U.DISTRITO_PESSOA = O.DISTRITO
   ORDER BY DBMS_RANDOM.VALUE
) WHERE ROWNUM <= 30;
