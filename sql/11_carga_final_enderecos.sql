-- 2. Sequences à frente dos IDs existentes (como DBA ou dono)
-------------------------------------------------------------------------------
-- As procedures às vezes recriavam sequences. Se alguma estiver ATRÁS do MAX(ID),
-- a carga daria "unique constraint violated". Esta consulta mostra a situação.

SELECT 'DBO_CC_ENDERECOS.SEQ_DISTRITOS' SEQ,
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_DISTRITOS') PROXIMO,
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.DISTRITOS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.DISTRITOS)) MAX_ID
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_BAIRROS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_BAIRROS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.BAIRROS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.BAIRROS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_DADOS_BAIRROS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_DADOS_BAIRROS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.DADOS_BAIRROS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.DADOS_BAIRROS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_LOGRADOUROS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_LOGRADOUROS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.LOGRADOUROS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.LOGRADOUROS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_DADOS_LOGRADOUROS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_DADOS_LOGRADOUROS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.DADOS_LOGRADOUROS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.DADOS_LOGRADOUROS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CCM_PESSOAS.SEQ_CEPS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CCM_PESSOAS' AND SEQUENCE_NAME = 'SEQ_CEPS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.CEPS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.CEPS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_LOGRADOUROS_CEPS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_LOGRADOUROS_CEPS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.LOGRADOUROS_CEPS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.LOGRADOUROS_CEPS))
  FROM DUAL
UNION ALL
SELECT 'DBO_CC_ENDERECOS.SEQ_BAIRROS_CEPS',
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'DBO_CC_ENDERECOS' AND SEQUENCE_NAME = 'SEQ_BAIRROS_CEPS'),
       GREATEST((SELECT NVL(MAX(ID), 0) FROM DBO_CC_ENDERECOS.BAIRROS_CEPS),
                (SELECT NVL(MAX(ID), 0) FROM DBO_CCM_PESSOAS.BAIRROS_CEPS))
  FROM DUAL;
