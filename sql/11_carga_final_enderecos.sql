-- 4. Conferências depois da carga
-------------------------------------------------------------------------------

-- 4.1 Código CCM na consolidada que não existe na final (deve ser 0)
SELECT 'BAIRROS' NIVEL, COUNT(*) QTD
  FROM DBO_UNI_PESSOAS.BAIRROS U
 WHERE U.CODIGO_CCM > 0
   AND NOT EXISTS (SELECT 1 FROM DBO_CCM_PESSOAS.BAIRROS F WHERE F.ID = U.CODIGO_CCM)
UNION ALL
SELECT 'LOGRADOUROS', COUNT(*)
  FROM DBO_UNI_PESSOAS.LOGRADOUROS U
 WHERE U.CODIGO_CCM > 0
   AND NOT EXISTS (SELECT 1 FROM DBO_CCM_PESSOAS.LOGRADOUROS F WHERE F.ID = U.CODIGO_CCM)
UNION ALL
SELECT 'CEPS', COUNT(*)
  FROM DBO_UNI_PESSOAS.CEPS U
 WHERE U.CODIGO_CCM > 0
   AND NOT EXISTS (SELECT 1 FROM DBO_CCM_PESSOAS.CEPS F WHERE F.ID = U.CODIGO_CCM);

-- 4.2 Logradouros carregados com tipo NEC (não encontrado em TIPOS_LOGRADOUROS)
SELECT U.TIPO_LOGRAD_DESC, U.TIPO_LOGRADOURO, COUNT(*) QTD
  FROM DBO_UNI_PESSOAS.LOGRADOUROS U
  JOIN DBO_CCM_PESSOAS.LOGRADOUROS F ON F.ID = U.CODIGO_CCM
  JOIN DBO_CC_ENDERECOS.TIPOS_LOGRADOUROS T ON T.ID = F.TIPO_LOGRADOURO_ID
 WHERE UPPER(TRIM(T.SIGLA)) = 'NEC'
 GROUP BY U.TIPO_LOGRAD_DESC, U.TIPO_LOGRADOURO
 ORDER BY 3 DESC;

-- 4.3 Mesmo ID nos dois schemas (deve ser 0)
SELECT COUNT(*) LOGRADOUROS_SO_EM_UM_SCHEMA
  FROM DBO_CC_ENDERECOS.LOGRADOUROS E
 WHERE NOT EXISTS (SELECT 1 FROM DBO_CCM_PESSOAS.LOGRADOUROS M WHERE M.ID = E.ID);
