-- 0. ANTES DE TUDO: quantos estão sem CODIGO_CCM (rode e me mande se assustar)
-------------------------------------------------------------------------------
-- Como as tabelas finais já estão carregadas, o normal é um número pequeno
-- (o que entrou pela unificação/consolidação nova). Se der perto do total,
-- o CODIGO_CCM foi apagado em algum momento: NÃO rode a carga e me avise,
-- porque ela criaria IDs novos para endereços que já existem.

SELECT 'DISTRITOS' NIVEL, COUNT(*) TOTAL,
       SUM(CASE WHEN NVL(CODIGO_CCM, 0) = 0 THEN 1 ELSE 0 END) SEM_CODIGO
  FROM DBO_UNI_PESSOAS.DISTRITOS
UNION ALL
SELECT 'BAIRROS', COUNT(*), SUM(CASE WHEN NVL(CODIGO_CCM, 0) = 0 THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.BAIRROS
UNION ALL
SELECT 'LOGRADOUROS', COUNT(*), SUM(CASE WHEN NVL(CODIGO_CCM, 0) = 0 THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.LOGRADOUROS
UNION ALL
SELECT 'CEPS', COUNT(*), SUM(CASE WHEN NVL(CODIGO_CCM, 0) = 0 THEN 1 ELSE 0 END)
  FROM DBO_UNI_PESSOAS.CEPS;

